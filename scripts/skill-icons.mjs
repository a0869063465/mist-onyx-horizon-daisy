// Copies the skill icons the game uses out of the game-icons.net set (CC BY 3.0) into src/lib/skill-icons.ts.
// Usage: npm pack @iconify-json/game-icons, untar it, then
//   node scripts/skill-icons.mjs path/to/package/icons.json
import fs from "node:fs";

const source = process.argv[2];
if (!source) throw new Error("Pass the path to @iconify-json/game-icons icons.json");
const set = JSON.parse(fs.readFileSync(source, "utf8"));
const book = fs.readFileSync(new URL("../src/lib/skill-book.ts", import.meta.url), "utf8");
const names = new Set([...book.matchAll(/\b(?:A|P|R|S|AP|PP|RP|SP)\("[^"]+", "([^"]+)"/g)].map((hit) => hit[1]));
// Action buttons on the monster sheet.
for (const extra of ["candle-skull", "info", "broadsword", "card-draw", "spell-book", "sands-of-time", "check-mark", "magic-swirl", "sparkles"]) names.add(extra);
// Deck builder: search, monster / spell / save / stats / filter buttons, the balance icon, the spell kind and the filter icons.
for (const extra of ["magnifying-glass", "wolf-head", "save", "histogram", "funnel", "scales", "mountains", "card-joker", "spiky-explosion", "crossed-swords", "checked-shield", "three-friends", "growth"]) names.add(extra);
// Chọn bộ bài: favourite, edit, delete, tutorial, new deck, and the game modes.
for (const extra of ["round-star", "quill-ink", "trash-can", "help", "card-play", "robot-golem", "shaking-hands", "test-tubes", "padlock", "portrait"]) names.add(extra);
const out = {};
for (const name of [...names].sort()) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Missing icon ${name}`);
  out[name] = icon.body;
}
const lines = Object.entries(out).map(([name, body]) => `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`);
fs.writeFileSync(
  new URL("../src/lib/skill-icons.ts", import.meta.url),
  `/**
 * Skill icons from game-icons.net by Lorc, Delapouite and contributors, licensed CC BY 3.0
 * (https://creativecommons.org/licenses/by/3.0/). Generated by scripts/skill-icons.mjs; do not edit by hand.
 * Each value is the inner SVG of a 512 × 512 icon.
 */
export const SKILL_ICONS: Record<string, string> = {
${lines.join("\n")}
};
`,
);
console.log(`${Object.keys(out).length} icons`);
